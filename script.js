const LANGUAGE_STORAGE_KEY = "securewise-language";

let currentLanguage = "en";
let currentQuestion = 0;
let score = 0;
let answered = false;
let selectedAnswer = null;
let quizScreen = "welcome";

const quizContent = document.getElementById("quiz-content");
const questionCounter = document.getElementById("question-counter");
const progressFill = document.getElementById("progress-fill");
const quizProgress = document.getElementById("quiz-progress");
const menuToggle = document.querySelector(".menu-toggle");
const nav = document.querySelector(".site-nav");
const languageButtons = document.querySelectorAll(".language-btn");

function getSavedLanguage() {
  try {
    return localStorage.getItem(LANGUAGE_STORAGE_KEY);
  } catch {
    return null;
  }
}

function saveLanguage(language) {
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  } catch {
    return;
  }
}

function t(key) {
  return translations[currentLanguage][key] ?? translations.en[key] ?? key;
}

function translateStaticContent() {
  document.documentElement.lang = currentLanguage === "pt" ? "pt-BR" : "en";
  document.title = t("pageTitle");

  const description = document.querySelector('meta[name="description"]');

  if (description) {
    description.setAttribute("content", t("metaDescription"));
  }

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    element.setAttribute("aria-label", t(element.dataset.i18nAria));
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    element.setAttribute("alt", t(element.dataset.i18nAlt));
  });
}

function updateLanguageButtons() {
  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === currentLanguage;

    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
}

function setLanguage(language) {
  if (!translations[language]) {
    return;
  }

  currentLanguage = language;
  saveLanguage(language);
  translateStaticContent();
  updateLanguageButtons();
  renderQuiz();
}

function updateProgress(completedQuestions) {
  const percentage = (completedQuestions / quizQuestions.length) * 100;

  progressFill.style.width = `${percentage}%`;
  quizProgress.setAttribute("aria-valuenow", String(completedQuestions));
}

function createElement(tag, className = "", text) {
  const element = document.createElement(tag);

  if (className) {
    element.className = className;
  }

  if (text !== undefined) {
    element.textContent = text;
  }

  return element;
}

function createButton(text, className, callback) {
  const button = createElement("button", className, text);

  button.type = "button";
  button.addEventListener("click", callback);

  return button;
}

function renderWelcome() {
  questionCounter.textContent = t("quizReady");
  updateProgress(0);
  quizContent.replaceChildren();

  const wrapper = createElement("div", "quiz-welcome");
  const symbol = createElement("div", "quiz-symbol", "◈");
  const title = createElement("h3", "", t("quizWelcomeTitle"));
  const description = createElement("p", "", t("quizWelcomeDescription"));

  symbol.setAttribute("aria-hidden", "true");

  const startButton = createButton(
    `${t("beginChallenge")} ↗`,
    "button button-primary",
    startQuiz
  );

  wrapper.append(symbol, title, description, startButton);
  quizContent.append(wrapper);
}

function renderQuestion() {
  const questionData = quizQuestions[currentQuestion];
  const content = questionData[currentLanguage];

  questionCounter.textContent =
    `${t("questionCounter")} ${String(currentQuestion + 1).padStart(2, "0")} / ${quizQuestions.length}`;

  updateProgress(currentQuestion + (answered ? 1 : 0));
  quizContent.replaceChildren();

  const wrapper = createElement("div", "quiz-question");
  const title = createElement("h3", "", content.question);
  const options = createElement("div", "quiz-options");
  const feedback = createElement("div", "quiz-feedback");

  feedback.setAttribute("role", "status");
  feedback.hidden = !answered;

  const nextButton = createButton(
    currentQuestion === quizQuestions.length - 1
      ? t("seeResults")
      : t("nextQuestion"),
    "button button-primary quiz-next",
    nextQuestion
  );

  nextButton.hidden = !answered;

  content.options.forEach((optionText, index) => {
    const letter = String.fromCharCode(65 + index);

    const optionButton = createButton(
      `${letter}. ${optionText}`,
      "quiz-option",
      () => selectAnswer(index)
    );

    optionButton.setAttribute(
      "aria-label",
      `${t("questionOptionLabel")} ${letter}: ${optionText}`
    );

    if (answered) {
      optionButton.disabled = true;

      if (index === questionData.correct) {
        optionButton.classList.add("correct");
      } else if (index === selectedAnswer) {
        optionButton.classList.add("incorrect");
      }
    }

    options.append(optionButton);
  });

  if (answered) {
    const wasCorrect = selectedAnswer === questionData.correct;

    feedback.textContent =
      `${wasCorrect ? t("correctAnswer") : t("incorrectAnswer")} ${content.explanation}`;
  }

  wrapper.append(title, options, feedback, nextButton);
  quizContent.append(wrapper);
}

function selectAnswer(index) {
  if (answered) {
    return;
  }

  answered = true;
  selectedAnswer = index;

  if (index === quizQuestions[currentQuestion].correct) {
    score++;
  }

  renderQuestion();
}

function nextQuestion() {
  if (!answered) {
    return;
  }

  currentQuestion++;
  answered = false;
  selectedAnswer = null;

  quizScreen = currentQuestion < quizQuestions.length ? "question" : "results";
  renderQuiz();
}

function renderResults() {
  questionCounter.textContent = t("challengeComplete");
  updateProgress(quizQuestions.length);
  quizContent.replaceChildren();

  const wrapper = createElement("div", "quiz-results");
  const scoreText = createElement("div", "score", `${score}/${quizQuestions.length}`);
  const title = createElement("h3");

  if (score === quizQuestions.length) {
    title.textContent = t("perfectResult");
  } else if (score >= 7) {
    title.textContent = t("goodResult");
  } else {
    title.textContent = t("learningResult");
  }

  const description = createElement("p", "", t("resultsDescription"));

  const restartButton = createButton(
    t("tryAgain"),
    "button button-primary",
    startQuiz
  );

  wrapper.append(scoreText, title, description, restartButton);
  quizContent.append(wrapper);
}

function renderQuiz() {
  if (quizScreen === "welcome") {
    renderWelcome();
  } else if (quizScreen === "question") {
    renderQuestion();
  } else {
    renderResults();
  }
}

function startQuiz() {
  currentQuestion = 0;
  score = 0;
  answered = false;
  selectedAnswer = null;
  quizScreen = "question";

  renderQuiz();
}

